import assert from 'node:assert/strict'
import { mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { register } from 'node:module'
import { sessionFixture } from './session-fixture.mjs'
register(new URL('./ts-loader.mjs', import.meta.url), import.meta.url)
const { SessionManager } = await import('../src/host/sessions.ts')
const { BindingTracker } = await import('../src/host/binding.ts')
const { currentTarget } = await import('../src/host/current-target.ts')
const temporary = mkdtempSync(join(tmpdir(), 'dsh-session-review-'))
const options = { stateDir: join(temporary, 'state'), workspacePath: join(temporary, 'workspace') }
const fixture = sessionFixture(options.workspacePath)
try {
  const first = new SessionManager(fixture.ctx, options)
  const id = first.current()
  assert.equal(await first.ensureConversation(), id, '小窗打开前建立正式 Session')
  assert.deepEqual(fixture.calls.controllerCreate[0], { sessionId: id, workspaceId: 'quick-workspace' })
  assert.equal(fixture.live.get(id).presetMounted, true, '正式 controller 路径安装 preset')
  first.setDraft(id, '未发出的草稿 A')
  await first.send(id, '请解释特征空间与核空间的关系。')
  first.setDraft(id, '尚未提交的追问')
  const target = await first.context(id)
  assert.equal(target.answerText, '你好')
  assert.equal(target.requirementText, '请解释特征空间与核空间的关系。')
  assert.equal(fixture.calls.create[0].meta.cwd, options.workspacePath)
  assert.ok(fixture.calls.attach.includes(id))
  const record = fixture.stored.get(id)
  assert.equal(record.events.find(e => e.type === 'user/message').data.source.kind, 'user')
  assert.equal(fixture.calls.prompt[0].sessionId, id, '普通用户输入走正式 prompt admission')
  assert.equal(fixture.calls.prompt[0].content[0].text, '请解释特征空间与核空间的关系。')
  await first.dispose()
  assert.equal(fixture.live.has(id), true, '插件卸载不销毁 controller 所有的 Agent')
  assert.equal(fixture.calls.dispose.length, 0)
  fixture.live.delete(id) // Simulate a Host restart after checking plugin ownership.
  const second = new SessionManager(fixture.ctx, options)
  assert.equal(second.current(), id, '重启恢复同一会话')
  assert.equal(second.draft(id), '尚未提交的追问')
  await second.hydrate(id)
  assert.equal(second.view(id).at(-1).text, '你好')
  const bindings = new BindingTracker()
  const restored = await currentTarget(second, bindings)
  assert.equal(restored.sessionId, id, '小窗恢复后自动关联正在显示的会话')
  assert.equal(restored.answerId, target.answerId, '反馈对应持久化的正式回答，而不是临时显示编号')
  await second.send(id, '我对上一条答案不满意，请自查并再改一轮。')
  assert.equal(second.draft(id),'尚未提交的追问','轮盘反馈不能删掉用户尚未发送的草稿')
  assert.equal(fixture.calls.create.length, 1)
  assert.equal(fixture.calls.resume.length, 1, '冷 Session 通过 controller 恢复并重新安装 preset')
  assert.equal(fixture.calls.resume[0].setup, 'preset-mounted')
  assert.notEqual((await second.context(id)).versionToken, target.versionToken)
  const revised = await currentTarget(second, bindings)
  assert.notEqual(revised.answerId, restored.answerId, '新回答完成后反馈跟随同一小窗的新回答')
  const feedbackTarget = await second.context(id)
  const feedback = { action: 'revise', requestId: 'wheel-revise-test', answerId: feedbackTarget.answerId, answerSeq: feedbackTarget.answerSeq, versionToken: feedbackTarget.versionToken, summary: '不满意，请改进一轮' }
  await second.send(id, '针对选定回答完成一轮改进。', { feedback })
  const feedbackEvents = fixture.stored.get(id).events
  const notice = feedbackEvents.findLast(e => e.type === 'user/message').data
  assert.equal(notice.source.kind, 'quick-help-feedback', '轮盘内部指令不能伪装成人工输入')
  assert.equal(notice.source.form, 'notice', '正式聊天使用可折叠 notice')
  assert.equal(notice.source.answerId, feedbackTarget.answerId, '绑定被评价的确切回答')
  assert.equal(notice.content[0].text, '针对选定回答完成一轮改进。', '实际模型输入仍完整记入会话')
  assert.ok(feedbackEvents.some(e => e.type === 'feedback/message-put' && e.data.item.rating === 'negative' && e.data.item.messageId === feedbackTarget.answerId), '不满意写入正式回答反馈')
  const shown = second.view(id).find(t => t.feedback)
  assert.equal(shown.text, feedback.summary, '小窗只显示简短反馈状态')
  assert.equal(shown.feedback.action, 'revise')
  assert.equal(second.draft(id), '尚未提交的追问')
  const feedbackReload = new SessionManager(fixture.ctx, options)
  await feedbackReload.hydrate(id)
  assert.equal(feedbackReload.view(id).find(t => t.feedback).text, feedback.summary, '重启后不恢复成长提示词气泡')
  await feedbackReload.dispose()
  fixture.live.get(id).followup({ id: 'composer-user', role: 'user', content: [{ type: 'text', text: '正式编辑器发送的内容' }], source: { kind: 'user' } })
  await new Promise(resolve => setTimeout(resolve, 0))
  const mdDir = join(options.workspacePath, '对话记录')
  const files = readdirSync(mdDir)
  assert.equal(files.length, 1)
  const md = readFileSync(join(mdDir, files[0]), 'utf8')
  assert.ok(md.includes(id) && md.includes('不满意') && md.includes('你好') && md.includes('正式编辑器发送的内容'), '正式 composer 的空闲事件自动导出 Markdown')
  assert.ok(md.includes('轮盘反馈') && !md.includes('针对选定回答完成一轮改进。'), 'Markdown 记录反馈摘要，完整指令仍在正式会话日志')
  const another = second.reset()
  const created = await second.navigateConversation(another)
  assert.notEqual(created, another, '新建会话有独立身份')
  assert.equal(fixture.live.get(created).presetMounted, true, '新建时先准备正式会话与预设')
  assert.equal(second.current(), created)
  await assert.rejects(second.navigateConversation(another, id), /已变化/, '过期小窗不能改变新窗口的会话')
  await assert.rejects(second.navigateConversation(created, 'unrelated-session'), /只能切换/, '拒绝任意工作区的会话 ID')
  assert.equal(second.current(), created, '切换拒绝时保留当前会话')
  assert.equal(await second.navigateConversation(created, id), id)
  assert.equal(second.draft(id), '尚未提交的追问', '切回后草稿按会话恢复')
  assert.equal(await second.navigateConversation(id, another), another)
  assert.ok(second.ownedConversations().some(item => item.sessionId === created), '空的新会话也可再次找到')
  assert.equal(await currentTarget(second, bindings), undefined, '新问题不能继续评价上一段会话')
  bindings.bind({ ...target, artifactLabel: '明确选择的桌面回答', kind: 'general', valid: true }, 'explicit')
  assert.equal((await currentTarget(second, bindings)).answerId, target.answerId, '明确选择的桌面回答不会被小窗默认值覆盖')
  bindings.clear()
  second.setDraft(another, '独立草稿 B')
  second.adopt(id)
  assert.equal(second.draft(another), '独立草稿 B')
  await assert.rejects(second.context(id, 'forged-answer'), /没有找到/)
  const parallel = await Promise.allSettled([second.send(id, '独占发送 A'), second.send(id, '并发发送 B')])
  assert.equal(parallel.filter(result => result.status === 'fulfilled').length, 1)
  assert.equal(parallel.filter(result => result.status === 'rejected').length, 1, '异步恢复前就预留发送权，不能两个writer')
  await second.send(id, '选定模型继续回答。', { modelRoute: 'provider/selected-model' })
  assert.equal(fixture.calls.selectModel.at(-1).model, 'selected-model', '显式模型覆盖走正式 controller')
  const start = record.events.length
  record.events.push({ type: 'turn/start', seq: start, time: Date.now(), data: {} })
  record.events.push({ type: 'assistant/message', seq: start + 1, time: Date.now(), surfaceOp: 'append', data: { message: { id: 'unfinished', content: [{ type: 'text', text: '尚未完成' }] } } })
  await assert.rejects(second.context(id, 'unfinished'), /尚未完成/)
  record.events.pop(); record.events.pop()
  const before = fixture.calls.create.length
  await assert.rejects(second.hydrate('nonexistent'), /missing/)
  assert.equal(fixture.calls.create.length, before, '读取不存在会话不能创建空壳')
  second.adopt('missing-external-session')
  await assert.rejects(second.send('missing-external-session', '测试失效目标'), /session missing/, '精确抛出 controller resolveAgent 的错误')
  second.adopt(id)
  const png = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII='
  const imageSession = second.reset()
  await second.send(imageSession, '解释截图', { images: [{ type: 'image', mediaType: 'image/png', data: png, name: '屏幕截图.png' }] })
  const imageMessage = fixture.stored.get(imageSession).events.find(e => e.type === 'user/message').data
  assert.equal(imageMessage.content[1].type, 'image', '模型收到正式 image 块，而不是图片路径文本')
  assert.equal(imageMessage.content[1].attachment.attachmentId, 'fixture-image')
  assert.equal(fixture.calls.admit.length, 1, '发送时只进行一次官方附件 admission')
  assert.equal(second.view(imageSession)[0].images[0].attachmentId, 'fixture-image')
  assert.deepEqual((await second.readImage(imageSession, 'fixture-image')).data, Buffer.from(png, 'base64'))
  await assert.rejects(second.readImage(id, 'fixture-image'), /不属于/, '别的会话不能读取这张图')
  const imageMarkdown = readdirSync(mdDir).map(file => file.endsWith('.md') ? readFileSync(join(mdDir,file),'utf8') : '').find(text => text.includes(imageSession))
  assert.ok(imageMarkdown.includes('![截图](附件/'))
  assert.equal(readdirSync(join(mdDir,'附件')).length, 1, 'Markdown 附件副本与截图一同落盘')
  second.setStopped(imageSession,true)
  const recovered = new SessionManager(fixture.ctx, options)
  assert.equal(recovered.isStopped(imageSession),true,'显式停止状态跨重启保留')
  const adopted = await second.context(imageSession)
  const callsBeforeAdopt = fixture.calls.create.length + fixture.calls.resume.length
  await second.adoptAnswer({ ...adopted })
  assert.equal(fixture.calls.create.length + fixture.calls.resume.length,callsBeforeAdopt,'采纳不激活模型或创建会话')
  assert.equal(fixture.stored.get(imageSession).events.at(-1).type,'feedback/message-put','采纳写入正式 DSH 反馈日志')
  assert.equal(second.isAdopted(imageSession,adopted.answerId),true)
  const custom=join(temporary,'Obsidian','论文笔记')
  second.setRecordsPath(custom)
  assert.equal((await second.storageInfo()).recordsPath,custom)
  await second.hydrate(imageSession)
  assert.ok(readdirSync(custom).some(file=>file.endsWith('.md')),'指定目录中的后续写入')
  assert.ok(readdirSync(mdDir).some(file=>file.endsWith('.md')),'原目录中的记录保留')
  await second.send(imageSession, '明确的新问题继续会话')
  assert.equal(second.isStopped(imageSession),false,'正式用户输入可解除停止，轮盘内部反馈不能自行解除')
  await recovered.dispose()
  await second.dispose()
  console.log('Session persistence: restart, workspace attach, real source, revision record, separate drafts and stale target checks passed.')
} finally { rmSync(temporary, { recursive: true, force: true }) }
