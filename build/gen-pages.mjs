/**
 * Turns `src/host/ui/` into the `pages.ts` module the host imports.
 *
 * The overlay's documents live as real files rather than as template literals
 * because a `.js` page inside a TypeScript string needs every backtick, dollar
 * sign and backslash escaped, and the result is unreadable and easy to break
 * silently. Here they are ordinary JavaScript that a syntax checker can verify.
 *
 * Run by `build/build.mjs` before esbuild, so the generated module is never
 * edited by hand and never checked in.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, extname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const uiDir = join(root, 'src', 'host', 'ui')
const outFile = join(root, 'src', 'host', 'pages.ts')

/** How each source file is served. */
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
}

/** The overlay routes, in the order the desktop layer knows them. */
const ROUTES = ['wheel', 'ask', 'settings', 'feedback']

/** Read one file as a TypeScript string literal. */
function literal(text) {
  // JSON strings preserve source bytes after JavaScript parses the generated file.
  // String.raw would retain the backslashes used to escape template delimiters,
  // leaving a served script with invalid tokens such as \`.
  return JSON.stringify(text)
}

function main() {
  const files = readdirSync(uiDir)
  const entries = []
  for (const file of files.sort()) {
    const type = TYPES[extname(file)]
    if (type === undefined) continue
    const content = readFileSync(join(uiDir, file), 'utf8')
    entries.push({ name: file, type, literal: literal(content) })
  }

  const byName = new Map(entries.map(entry => [entry.name, entry]))
  const missing = ROUTES.flatMap(route => [`${route}.html`]).filter(name => !byName.has(name))
  if (missing.length > 0) {
    throw new Error(`src/host/ui 缺少文件：${missing.join('、')}`)
  }

  const documentFor = route => {
    const entry = byName.get(`${route}.html`)
    return entry.literal
  }

  const assetEntries = entries
    .filter(entry => extname(entry.name) !== '.html')
    .map(entry => `  ${JSON.stringify(entry.name)}: { type: ${JSON.stringify(entry.type)}, content: ${entry.literal} },`)
    .join('\n')

  const source = `/**
 * The overlay documents and their static files, generated from \`src/host/ui/\`.
 *
 * GENERATED by \`build/gen-pages.mjs\` — do not edit. Change the files under
 * \`src/host/ui/\` and rebuild.
 *
 * They are inlined rather than read from disk because the overlay is loaded over
 * the Host's HTTP surface (from \`dsh-app://app/quick-help/wheel\`), where a
 * \`file://\` path would not resolve and a missing file would leave the user
 * looking at an empty transparent window.
 *
 * @module @local/dsh-quick-help/host/pages
 */

/** One page's document, keyed by the route the desktop layer opens. */
export const SLOTS = {
${ROUTES.map(route => `  ${route}: { html: ${documentFor(route)} },`).join('\n')}
} as const

/** The overlay's own static files, served by exact name. */
const ASSETS: Readonly<Record<string, { type: string; content: string }>> = {
${assetEntries}
}

/** Serves the overlay's documents and static files. */
export const PAGES: {
  asset(name: string): { type: string; content: string } | undefined
  names(): string[]
} = {
  /**
   * @param name - File name, without a path.
   * @returns The file, or \`undefined\` for anything not listed above.
   */
  asset(name: string) {
    // \`hasOwnProperty\` rather than a truthy check: a name like \`toString\` must
    // not resolve to something inherited from the prototype.
    return Object.prototype.hasOwnProperty.call(ASSETS, name) ? ASSETS[name] : undefined
  },
  names(): string[] {
    return Object.keys(ASSETS)
  },
}
`

  mkdirSync(dirname(outFile), { recursive: true })
  writeFileSync(outFile, source)
  const count = entries.length
  const bytes = Buffer.byteLength(source)
  console.log(`generated src/host/pages.ts  ${count} 个资源  ${(bytes / 1024).toFixed(0)} KiB`)
}

main()
