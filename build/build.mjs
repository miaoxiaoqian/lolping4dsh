/**
 * Build script for the quick-help bundle.
 *
 * Three steps, in order:
 *
 *  1. `gen-pages.mjs` turns `src/host/ui/` into `src/host/pages.ts`. The overlay's
 *     documents have to be inlined — they are served over HTTP, so a `file://`
 *     path would not resolve — and generating that module beats writing it by
 *     hand, because the page scripts stay real JavaScript that `node --check`
 *     can verify.
 *  2. esbuild produces `lib/index.js`, the plain ESM plugin the Loader requires.
 *  3. esbuild produces `lib/client.js`, the `window.__ModuleLoader__` factory the
 *     Harness Client module table consumes. That half contributes one sidebar row
 *     and the settings page behind it.
 */
import { build } from 'esbuild'
import { readFileSync, readdirSync, rmSync, mkdirSync, cpSync, existsSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { execFileSync } from 'node:child_process'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const out = join(root, 'lib')

/** Platform seed modules: the browser module table already owns these. */
const CLIENT_SEED = new Set([
  'react', 'react/jsx-runtime', 'react-dom', 'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
])

/**
 * Registration wrapper for the browser half.
 *
 * esbuild has no `intro` option, so the CJS prelude a `require`-based body needs
 * rides at the end of the banner — emitted immediately inside the factory, which is
 * the place the loader's own bundler puts it.
 */
function registration() {
  const id = JSON.stringify('@local/dsh-quick-help')
  return {
    banner: `window.__ModuleLoader__.load({ id: ${id}, factory: (require) => {\nvar module = { exports: {} }; var exports = module.exports;`,
    footer: 'return module.exports; } });',
  }
}

async function main() {
  execFileSync(process.execPath, [join(root, 'build', 'gen-pages.mjs')], { stdio: 'inherit' })

  rmSync(out, { recursive: true, force: true })
  mkdirSync(out, { recursive: true })

  // Host half. Node builtins stay external (esbuild's `platform: 'node'`
  // default); everything else is inlined. A profile-installed bundle is linked
  // with `link:`, so a bare specifier would have to resolve from this package's
  // real directory — bundling makes the artifact depend on nothing but Node.
  await build({
    entryPoints: [join(root, 'src/host/index.ts')],
    outfile: join(out, 'index.js'),
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: ['node22'],
    external: ['node:*'],
    sourcemap: false,
    logLevel: 'info',
    banner: { js: '// @local/dsh-quick-help — Host half. Generated by build/build.mjs.' },
  })

  // Browser half.
  const reg = registration()
  await build({
    entryPoints: [join(root, 'src/client/index.tsx')],
    outfile: join(out, 'client.js'),
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120'],
    external: [...CLIENT_SEED],
    sourcemap: false,
    logLevel: 'info',
    // `react/jsx-runtime` is a seed module of the Harness Client table, so the
    // automatic runtime keeps every component on the React instance the
    // application already owns instead of bundling a second copy.
    jsx: 'automatic',
    define: { 'import.meta.url': '""' },
    banner: { js: reg.banner },
    footer: { js: reg.footer },
  })

  // The native input helper is a separate architecture-specific binary, so it
  // ships as a file rather than as part of the bundle. Its absence is reported
  // by the desktop layer rather than crashing the plugin at import time.
  const helper = join(root, 'build', 'input-helper')
  if (existsSync(helper)) {
    cpSync(helper, join(out, 'input-helper'))
    console.log(`copied lib/input-helper  ${(statSync(helper).size / 1024).toFixed(0)} KiB`)
  } else {
    console.warn('warning: build/input-helper is missing; the wheel cannot capture the mouse until it is built')
    console.warn('         run native/input-helper/build-helper.sh')
  }

  // Assets stay where they are rather than being copied into lib/, because they
  // are 18 MB of League files that are never re-encoded and never inlined. The
  // host resolves them from `<package>/assets`.
  const assets = join(root, 'assets')
  if (existsSync(assets)) {
    const count = countFiles(assets)
    console.log(`assets/  ${count} 个文件（按需加载，不打包进 .app）`)
  } else {
    console.warn(`warning: ${assets} is missing; every slot will report its asset as absent`)
  }

  for (const file of ['index.js', 'client.js']) {
    const bytes = readFileSync(join(out, file)).byteLength
    console.log(`built lib/${file}  ${(bytes / 1024).toFixed(0)} KiB`)
  }
}

/** Count files under a directory, for the build summary. */
function countFiles(dir) {
  let total = 0
  for (const entry of readdirSync(dir, { withFileTypes: true, recursive: true })) {
    if (entry.isFile()) total += 1
  }
  return total
}

await main()
